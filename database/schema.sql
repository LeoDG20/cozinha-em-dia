-- Esquema do banco PostgreSQL (equivalente ao gerado pelo Hibernate).
-- A aplicação cria estas tabelas sozinha ao iniciar (spring.jpa.hibernate.ddl-auto=update);
-- este arquivo serve como referência e permite criar o esquema manualmente.

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS receitas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  nome VARCHAR(120) NOT NULL,
  descricao VARCHAR(500),
  modo_preparo TEXT NOT NULL,
  tempo_preparo_min INTEGER,
  porcoes INTEGER,
  imagem_arquivo VARCHAR(80),
  imagem_url VARCHAR(500),
  video_url VARCHAR(300),
  video_arquivo VARCHAR(80),
  origem_nome VARCHAR(120)
);
CREATE TABLE IF NOT EXISTS ingredientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS receita_ingredientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receita_id BIGINT NOT NULL REFERENCES receitas(id),
  ingrediente_id BIGINT NOT NULL REFERENCES ingredientes(id),
  quantidade DOUBLE PRECISION NOT NULL,
  unidade VARCHAR(20) NOT NULL,
  UNIQUE (receita_id, ingrediente_id)
);
CREATE TABLE IF NOT EXISTS etapas_receita (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receita_id BIGINT NOT NULL REFERENCES receitas(id),
  ordem INTEGER NOT NULL,
  descricao TEXT NOT NULL,
  imagem_arquivo VARCHAR(80)
);
CREATE TABLE IF NOT EXISTS compartilhamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receita_id BIGINT NOT NULL REFERENCES receitas(id),
  destino_id BIGINT NOT NULL REFERENCES usuarios(id),
  mensagem VARCHAR(200),
  criado_em TIMESTAMP NOT NULL,
  copiada BOOLEAN NOT NULL,
  UNIQUE (receita_id, destino_id)
);
CREATE TABLE IF NOT EXISTS despensa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  ingrediente_id BIGINT NOT NULL REFERENCES ingredientes(id),
  quantidade DOUBLE PRECISION NOT NULL,
  unidade VARCHAR(20) NOT NULL,
  UNIQUE (usuario_id, ingrediente_id)
);
